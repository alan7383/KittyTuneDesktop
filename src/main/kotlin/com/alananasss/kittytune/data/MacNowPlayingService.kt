package com.alananasss.kittytune.data

import com.alananasss.kittytune.domain.Track
import java.io.Closeable
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch
import java.io.File
import java.io.PrintWriter
import kotlin.concurrent.thread

class MacNowPlayingService(
    private val onPlay: () -> Unit,
    private val onPause: () -> Unit,
    private val onNext: () -> Unit,
    private val onPrevious: () -> Unit,
    private val onSeek: (Long) -> Unit,
    private val onPlayPause: (() -> Unit)? = null
) : Closeable {

    private val mainScope = CoroutineScope(SupervisorJob() + Dispatchers.Main)
    private var process: Process? = null
    private var writer: PrintWriter? = null
    private var lastUpdate: String? = null

    init {
        if (System.getProperty("os.name").lowercase().contains("mac")) {
            runCatching { start() }.onFailure {
                System.err.println("Mac Now Playing: ${it.message}")
            }
        }
    }

    private fun start() {
        // In a packaged Compose app, java.home lives under MyApp.app/Contents/runtime.
        // For `./gradlew run`, use the helper generated by scripts/build-macos-nowplaying.sh.
        val packagedApp = generateSequence(File(System.getProperty("java.home"))) {
            it.parentFile
        }.firstOrNull { folder ->
            folder.name.endsWith(".app") && File(folder, "Contents/Info.plist").isFile
        }

        val overridePath = System.getenv("KITTYTUNE_NOWPLAYING_HELPER")
        val helperBinary = when {
            !overridePath.isNullOrBlank() -> File(overridePath)
            packagedApp != null -> {
                val inHelpers = File(
                    packagedApp,
                    "Contents/Helpers/KittyTune-NowPlaying-Helper.app/Contents/MacOS/KittyTuneNowPlaying"
                )
                val inResources = File(
                    packagedApp,
                    "Contents/Resources/KittyTune-NowPlaying-Helper.app/Contents/MacOS/KittyTuneNowPlaying"
                )
                if (inHelpers.exists()) inHelpers else inResources
            }
            else -> File(
                "build/macos-nowplaying/KittyTune-NowPlaying-Helper.app/Contents/MacOS/KittyTuneNowPlaying"
            ).absoluteFile
        }

        require(helperBinary.isFile && helperBinary.canExecute()) {
            "Now Playing helper is missing or not executable: $helperBinary. " +
                "Run scripts/build-macos-nowplaying.sh first."
        }

        val p = ProcessBuilder(helperBinary.absolutePath)
            .redirectErrorStream(true)
            .start()

        process = p

        writer = PrintWriter(
            p.outputStream.bufferedWriter(Charsets.UTF_8),
            true
        )

        thread(isDaemon = true, name = "MacNowPlaying-Reader") {
            runCatching {
                p.inputStream.bufferedReader(Charsets.UTF_8).forEachLine {
                    handleBridgeLine(it.trim())
                }
            }
        }
    }


    private fun handleBridgeLine(line: String) {
        val action: (() -> Unit)? = when {
            line == "CMD:PLAY" -> onPlay
            line == "CMD:PAUSE" -> onPause
            line == "CMD:TOGGLE" -> onPlayPause ?: onPlay
            line == "CMD:NEXT" -> onNext
            line == "CMD:PREV" -> onPrevious
            line.startsWith("SEEK:") ->
                line.removePrefix("SEEK:").toLongOrNull()?.let { ms ->
                    { onSeek(ms) }
                }
            else -> null
        }

        if (action != null) {
            mainScope.launch { action() }
        }
    }

    fun updateMedia(
        track: Track?,
        playing: Boolean,
        position: Long,
        duration: Long
    ) {
        val out = writer ?: return
        if (track == null) return

        val fields = listOf(
            "UPDATE",
            track.title.orEmpty(),
            track.displayArtist,
            (track.publisherMetadata?.albumTitle
                ?: track.publisherMetadata?.releaseTitle).orEmpty(),
            track.fullResArtwork.orEmpty(),
            if (playing) "1" else "0",
            position.coerceAtLeast(0).toString(),
            duration.coerceAtLeast(0).toString()
        )

        val message = fields.joinToString("\t") {
            it.replace(Regex("[\\t\\r\\n]"), " ")
        }

        if (message == lastUpdate) return

        lastUpdate = message
        out.println(message)
    }

    override fun close() {
        mainScope.cancel()
        runCatching { writer?.println("QUIT") }
        runCatching { writer?.close() }
        runCatching { process?.destroy() }

        writer = null
        process = null
    }
}
