"""Imports the Kitty pet from the Android app into KittyTune Desktop.

  python -I scripts/pet/import_android_pet.py <android repo root>

The Android generator (scripts/pet/gen_pet_sprites.py in the Android repo) stays the single source
of every drawing. This script turns its output into what the desktop needs:

  res/drawable/pet_*.xml + widget_pet_*.xml  ->  src/main/resources/pet/pet_sprites.bin
      Every sprite is a pixel grid exported as "Mx,yhWv1h-Wz" rectangles; the atlas keeps the same
      rectangles (colour + x, y, w, h), far smaller and faster to load than 2,300 vector files.
  res/raw/pet_partmap.bin                    ->  src/main/resources/pet/pet_partmap.bin (as is)
  res/drawable-nodpi/pet_ivy_photo.jpg       ->  src/main/resources/pet/pet_ivy_photo.jpg (as is)
  ui/widget/pet/PetFrames.kt                 ->  ui/pet/PetFrames.kt (R.drawable ids -> sprite names)
  ui/widget/pet/PetCoatPresets.kt            ->  ui/pet/PetCoatPresets.kt (package only)
  res/values*/strings.xml (pet_*, widget_pet_*, the setup bar's 4) -> src/main/resources/i18n/strings-<lang>.xml
      Replaces the block between the KITTY PET markers (appended once), so re-running is safe.

Atlas format (little endian):
  magic "KPS1", u16 sprite count, then per sprite:
  u8 name length, name (ascii), u8 width, u8 height, u16 path count,
  per path: u32 ARGB, u16 rect count, rect count * (u8 x, u8 y, u8 w, u8 h)
"""
import os
import re
import shutil
import struct
import sys
import xml.etree.ElementTree as ET

ANDROID = sys.argv[1]
DESKTOP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

RES = os.path.join(ANDROID, 'app', 'src', 'main', 'res')
JAVA_PET = os.path.join(ANDROID, 'app', 'src', 'main', 'java', 'com', 'alananasss', 'kittytune', 'ui', 'widget', 'pet')
OUT_RES = os.path.join(DESKTOP, 'src', 'main', 'resources', 'pet')
OUT_KT = os.path.join(DESKTOP, 'src', 'main', 'kotlin', 'com', 'alananasss', 'kittytune', 'ui', 'pet')
I18N = os.path.join(DESKTOP, 'src', 'main', 'resources', 'i18n')

ANDROID_NS = '{http://schemas.android.com/apk/res/android}'
RECT = re.compile(r'M(\d+),(\d+)h(\d+)v(\d+)h-\d+z')


def sprite_rects(path):
    root = ET.parse(path).getroot()
    if root.tag != 'vector':
        return None
    w = int(float(root.get(ANDROID_NS + 'viewportWidth')))
    h = int(float(root.get(ANDROID_NS + 'viewportHeight')))
    paths = []
    for p in root.iter('path'):
        color = p.get(ANDROID_NS + 'fillColor')
        data = p.get(ANDROID_NS + 'pathData')
        rects = [tuple(int(v) for v in m) for m in RECT.findall(data)]
        # every command must be a pixel rectangle: anything else would be silently lost
        assert RECT.sub('', data) == '', f'{path}: unexpected path data'
        argb = int(color.lstrip('#'), 16)
        if len(color) == 7:
            argb |= 0xFF000000
        paths.append((argb, rects))
    return w, h, paths


def build_atlas():
    drawable = os.path.join(RES, 'drawable')
    names = sorted(f for f in os.listdir(drawable)
                   if (f.startswith('pet_') or f.startswith('widget_pet_')) and f.endswith('.xml'))
    sprites = []
    for f in names:
        parsed = sprite_rects(os.path.join(drawable, f))
        if parsed is None:
            continue  # shapes (widget background), drawn by Compose on desktop
        key = f[:-4]
        key = key[4:] if key.startswith('pet_') else key
        sprites.append((key, parsed))
    out = bytearray(b'KPS1')
    out += struct.pack('<H', len(sprites))
    for key, (w, h, paths) in sprites:
        b = key.encode('ascii')
        out += struct.pack('<B', len(b)) + b + struct.pack('<BBH', w, h, len(paths))
        for argb, rects in paths:
            out += struct.pack('<IH', argb, len(rects))
            for x, y, rw, rh in rects:
                out += struct.pack('<BBBB', x, y, rw, rh)
    os.makedirs(OUT_RES, exist_ok=True)
    with open(os.path.join(OUT_RES, 'pet_sprites.bin'), 'wb') as fh:
        fh.write(out)
    print(f'atlas: {len(sprites)} sprites, {len(out)} bytes')


def copy_raw():
    shutil.copyfile(os.path.join(RES, 'raw', 'pet_partmap.bin'), os.path.join(OUT_RES, 'pet_partmap.bin'))
    shutil.copyfile(os.path.join(RES, 'drawable-nodpi', 'pet_ivy_photo.jpg'), os.path.join(OUT_RES, 'pet_ivy_photo.jpg'))


HEADER = ('// GENERATED by scripts/pet/import_android_pet.py from the Android PetFrames.kt '
          '(itself generated by gen_pet_sprites.py). Do not edit by hand.\n')


def port_frames():
    src = open(os.path.join(JAVA_PET, 'PetFrames.kt'), encoding='utf-8').read()
    src = src.split('\n', 1)[1]  # drop the Android "GENERATED" line
    src = src.replace('package com.alananasss.kittytune.ui.widget.pet', 'package com.alananasss.kittytune.ui.pet')
    src = src.replace('import com.alananasss.kittytune.R\n', '')
    src = re.sub(r'R\.drawable\.pet_(\w+)', r'"\1"', src)
    # ids become sprite names; "no layer" (0) becomes null
    src = src.replace('intArrayOf(', 'arrayOf<String?>(')
    src = re.sub(r'(?<=[(,] )0(?=[,)])|(?<=\()0(?=[,)])', 'null', src)
    # ...but the accessory key (the Int before hatOk / neckOk) can legitimately be 0
    src = re.sub(r'null(?=, (?:true|false), (?:true|false)\)\))', '0', src)
    src = src.replace('Map<String, IntArray>', 'Map<String, Array<String?>>')
    src = src.replace('val rooms: Map<String, Int>', 'val rooms: Map<String, String>')
    src = src.replace('val decor: Map<String, Int>', 'val decor: Map<String, String>')
    src = src.replace(
        '    val fur: Int, val shade: Int, val eye: Int, val ink: Int,\n    val marks: IntArray, val whites: IntArray,',
        '    val fur: String?, val shade: String?, val eye: String?, val ink: String?,\n    val marks: Array<String?>, val whites: Array<String?>,')
    src = src.replace('(0 = none)', '(null = none)')
    assert 'R.drawable' not in src and 'IntArray' not in src, 'PetFrames port incomplete'
    os.makedirs(OUT_KT, exist_ok=True)
    with open(os.path.join(OUT_KT, 'PetFrames.kt'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(HEADER + src)

    presets = open(os.path.join(JAVA_PET, 'PetCoatPresets.kt'), encoding='utf-8').read().split('\n', 1)[1]
    presets = presets.replace('package com.alananasss.kittytune.ui.widget.pet', 'package com.alananasss.kittytune.ui.pet')
    with open(os.path.join(OUT_KT, 'PetCoatPresets.kt'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(HEADER + presets)


LANGS = {'en': 'values', 'fr': 'values-fr', 'de': 'values-de', 'hu': 'values-hu',
         'ru': 'values-ru', 'tr': 'values-tr', 'vi': 'values-vi'}
BEGIN = '    <!-- KITTY PET (imported from Android by scripts/pet/import_android_pet.py) -->'
END = '    <!-- /KITTY PET -->'
# pet strings, plus the few strings of the Android setup bottom bar the pet setup reuses
PET_LINE = re.compile(r'^\s*<string name="(?:(?:pet_|widget_pet_)[^"]*|setup_lets_go|setup_finish_btn|setup_step_format|common_next)"[^>]*>.*?</string>\s*$', re.M)


def merge_strings():
    for lang, folder in LANGS.items():
        android = open(os.path.join(RES, folder, 'strings.xml'), encoding='utf-8').read()
        lines = [m.group(0).strip() for m in PET_LINE.finditer(android)]
        target = os.path.join(I18N, f'strings-{lang}.xml')
        desk = open(target, encoding='utf-8').read()
        block = BEGIN + '\n' + '\n'.join('    ' + l for l in lines) + '\n' + END + '\n'
        if BEGIN in desk:
            desk = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n', lambda _: block, desk, flags=re.S)
        else:
            idx = desk.rindex('</resources>')
            desk = desk[:idx] + block + desk[idx:]
        with open(target, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(desk)
        print(f'strings-{lang}: {len(lines)} pet strings')


build_atlas()
copy_raw()
port_frames()
merge_strings()
